-- Map quiz result records to the e-learning quiz permission.
-- Align new logistics workflow stores with module-level RBAC.
CREATE OR REPLACE FUNCTION private.ks_module_for_store(p_store text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path TO ''
AS $function$
  SELECT CASE p_store
    WHEN 'produtos' THEN 'produtos'
    WHEN 'unidades' THEN 'produtos'
    WHEN 'avaliacoes' THEN 'produtos-avaliacoes'
    WHEN 'clientes' THEN 'clientes'
    WHEN 'clientesPortal' THEN 'portal-cliente'
    WHEN 'fornecedores' THEN 'fornecedores'
    WHEN 'transportadoras' THEN 'transportadoras'
    WHEN 'vendas' THEN 'vendas'
    WHEN 'devolucoes' THEN 'vendas'
    WHEN 'vendasConsignadas' THEN 'vendas-consignadas'
    WHEN 'promocoes' THEN 'vendas-promocoes'
    WHEN 'tabelasPrecos' THEN 'tabelas-precos'
    WHEN 'orcamentos' THEN 'orcamentos'
    WHEN 'compras' THEN 'compras'
    WHEN 'recebimentos' THEN 'compras'
    WHEN 'aprovacoes' THEN 'compras'
    WHEN 'estoque' THEN 'estoque'
    WHEN 'movimentacoesEstoque' THEN 'estoque'
    WHEN 'transferencias' THEN 'estoque'
    WHEN 'inventarios' THEN 'estoque'
    WHEN 'lotes' THEN 'estoque'
    WHEN 'pecasEstoque' THEN 'estoque'
    WHEN 'contasReceber' THEN 'financeiro'
    WHEN 'contasPagar' THEN 'financeiro'
    WHEN 'pagamentos' THEN 'financeiro'
    WHEN 'planoContas' THEN 'financeiro'
    WHEN 'budgets' THEN 'financeiro'
    WHEN 'forecasts' THEN 'financeiro'
    WHEN 'conciliacoes' THEN 'financeiro'
    WHEN 'transacoesBancarias' THEN 'financeiro'
    WHEN 'previsoesVendas' THEN 'financeiro'
    WHEN 'tendencias' THEN 'financeiro'
    WHEN 'faturas' THEN 'fiscal'
    WHEN 'documentosFiscais' THEN 'fiscal'
    WHEN 'integracoesAGT' THEN 'fiscal'
    WHEN 'ivas' THEN 'fiscal'
    WHEN 'irts' THEN 'fiscal'
    WHEN 'funcionarios' THEN 'rh'
    WHEN 'folhasPagamento' THEN 'rh'
    WHEN 'ferias' THEN 'rh'
    WHEN 'beneficios' THEN 'rh'
    WHEN 'planosCarreira' THEN 'rh-plano-carreira'
    WHEN 'departamentos' THEN 'rh'
    WHEN 'feriasFuncionarios' THEN 'rh'
    WHEN 'pagamentosFuncionarios' THEN 'rh'
    WHEN 'vagas' THEN 'rh-recrutamento'
    WHEN 'candidatos' THEN 'rh-recrutamento'
    WHEN 'desempenhoRH' THEN 'rh-desempenho'
    WHEN 'onboarding' THEN 'rh-onboarding'
    WHEN 'turnos' THEN 'rh-ponto'
    WHEN 'pontoDigital' THEN 'rh-ponto'
    WHEN 'frequencias' THEN 'rh-ponto'
    WHEN 'rescisoes' THEN 'rh-rescisao'
    WHEN 'producao' THEN 'producao'
    WHEN 'ordensProducao' THEN 'ordens-producao'
    WHEN 'mrp' THEN 'mrp'
    WHEN 'boms' THEN 'bom'
    WHEN 'custosProducao' THEN 'custos-producao'
    WHEN 'controleQualidade' THEN 'controle-qualidade'
    WHEN 'planosProducao' THEN 'planos-producao'
    WHEN 'projetos' THEN 'projetos'
    WHEN 'tarefas' THEN 'projetos-tarefas'
    WHEN 'tarefasProjetos' THEN 'projetos-tarefas'
    WHEN 'ganttProjetos' THEN 'projetos-gantt'
    WHEN 'timesheets' THEN 'projetos-timesheet'
    WHEN 'membrosProjetos' THEN 'projetos-recursos'
    WHEN 'atividadesProjetos' THEN 'projetos'
    WHEN 'ativos' THEN 'ativos'
    WHEN 'depreciacoes' THEN 'ativos-depreciacao'
    WHEN 'manutencoesAtivos' THEN 'ativos-manutencao'
    WHEN 'garantias' THEN 'ativos-garantia'
    WHEN 'frotas' THEN 'frota'
    WHEN 'motoristas' THEN 'frota'
    WHEN 'manutencoes' THEN 'frota-manutencao'
    WHEN 'frotaRotas' THEN 'frota-rotas'
    WHEN 'gpsTracking' THEN 'frota-gps'
    WHEN 'abastecimentos' THEN 'frota-combustivel'
    WHEN 'multas' THEN 'frota-multas'
    WHEN 'ordensServico' THEN 'os'
    WHEN 'ordensManutencao' THEN 'os-manutencao'
    WHEN 'checklistsInspecao' THEN 'os-checklist'
    WHEN 'calendarioManutencoes' THEN 'os-calendario'
    WHEN 'tecnicos' THEN 'os-tecnicos'
    WHEN 'historicoOS' THEN 'os'
    WHEN 'roteirizacao' THEN 'logistica-roteirizacao'
    WHEN 'picking' THEN 'logistica-picking'
    WHEN 'crossDocking' THEN 'logistica-crossdocking'
    WHEN 'frotaDocumentos' THEN 'frota-documentos'
    WHEN 'ddgHistorico' THEN 'logistica-roteirizacao'
    WHEN 'bingHistorico' THEN 'logistica-roteirizacao'
    WHEN 'etiquetas' THEN 'logistica-etiquetas'
    WHEN 'armazens' THEN 'logistica-armazens'
    WHEN 'rastreios' THEN 'logistica-rastreio'
    WHEN 'ecommerce' THEN 'ecommerce-vitrine'
    WHEN 'ecommerceProdutos' THEN 'ecommerce-produtos'
    WHEN 'ecommerceCarrinhos' THEN 'ecommerce-carrinho'
    WHEN 'ecommercePedidos' THEN 'ecommerce-pedidos'
    WHEN 'pagamentosEcommerce' THEN 'ecommerce-pagamento'
    WHEN 'carrinhosSalvos' THEN 'ecommerce-carrinho'
    WHEN 'campanhas' THEN 'marketing-campanhas'
    WHEN 'campanhasMarketing' THEN 'marketing-campanhas'
    WHEN 'eventos' THEN 'projetos'
    WHEN 'eventosCalendar' THEN 'projetos'
    WHEN 'leads' THEN 'crm'
    WHEN 'contatosWhatsApp' THEN 'crm'
    WHEN 'automacoes' THEN 'crm-automacao'
    WHEN 'scoreLeads' THEN 'crm-score'
    WHEN 'mensagensWhatsApp' THEN 'crm-automacao'
    WHEN 'templatesWhatsApp' THEN 'crm-automacao'
    WHEN 'segmentacoes' THEN 'clientes-segmentacao'
    WHEN 'cupons' THEN 'clientes-cupons'
    WHEN 'fidelidade' THEN 'clientes-fidelidade'
    WHEN 'mensagens' THEN 'notificacoes'
    WHEN 'mensagensChat' THEN 'notificacoes'
    WHEN 'notificacoes' THEN 'notificacoes'
    WHEN 'feedbacks' THEN 'notificacoes'
    WHEN 'cursos' THEN 'elearning-cursos'
    WHEN 'audiobooks' THEN 'elearning-cursos'
    WHEN 'certificacoes' THEN 'elearning-certificacoes'
    WHEN 'quizzes' THEN 'elearning-quizzes'
    WHEN 'quizResults' THEN 'elearning-quizzes'
    WHEN 'documentos' THEN 'documentos'
    WHEN 'contratos' THEN 'contratos'
    WHEN 'assinaturasDigitais' THEN 'contratos'
    WHEN 'tickets' THEN 'tickets'
    WHEN 'dashboardsCustom' THEN 'relatorios'
    WHEN 'auditoria' THEN 'auditoria'
    WHEN 'sincronizacao' THEN 'integracoes'
    WHEN 'backups' THEN 'config'
    WHEN 'backupsAgendados' THEN 'config'
    WHEN 'backupsNuvem' THEN 'config'
    WHEN 'modulosPersonalizados' THEN 'modulos'
    WHEN 'gruposUsuarios' THEN 'usuarios'
    WHEN 'servicos' THEN 'servicos'
    ELSE p_store
  END;
$function$;

